"""Build src/render/tex-fonts.js: subsets of MathJax's TeX fonts for the lab layout.

The fonts are Computer Modern as shipped with MathJax 3 (Apache License 2.0). Run
after changing the characters the lab card uses:

    npm pack mathjax@3.2.2 && tar -xzf mathjax-3.2.2.tgz
    pip install fonttools brotli
    python3 scripts/subset-tex-fonts.py package/es5/output/chtml/fonts/woff-v2
    npx prettier --write src/render/tex-fonts.js
"""

import base64
import io
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

LOWER = 'abcdefghijklmnopqrstuvwxyz'
# Only what the lab card sets, to keep every card small: upright digits, operators and
# words (weekday names, units), italic variables, and two AMS symbols.
FONTS = [
    (
        'MathJax_Main-Regular',
        'normal',
        ' 0123456789.,:;!?()[]|+=<>/*%-' + LOWER + 'FMSTW' + '−∫Σ∅⟨⟩∝ℓ·̂̄',
    ),
    ('MathJax_Math-Italic', 'italic', LOWER + 'CFGHLNPRST' + 'αθμστχ'),
    ('MathJax_AMS-Regular', 'normal', '∴★'),
]


def woff2(path, chars):
    font = TTFont(path)
    options = subset.Options()
    options.flavor = 'woff2'
    options.layout_features = ['*']
    options.name_IDs = ['*']
    subsetter = subset.Subsetter(options)
    cmap = font.getBestCmap()
    codes = sorted({ord(c) for c in chars if ord(c) in cmap})
    subsetter.populate(unicodes=codes)
    subsetter.subset(font)
    out = io.BytesIO()
    font.flavor = 'woff2'
    font.save(out)
    return out.getvalue(), codes


def unicode_ranges(codes):
    runs = []
    for code in codes:
        if runs and code == runs[-1][1] + 1:
            runs[-1][1] = code
        else:
            runs.append([code, code])
    return [f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in runs]


def main(folder):
    faces = []
    for name, style, chars in FONTS:
        data, codes = woff2(Path(folder) / f'{name}.woff', chars)
        ranges = ','.join(unicode_ranges(codes))
        src = base64.b64encode(data).decode()
        faces.append(
            f"  `@font-face{{font-family:ags-tex;font-style:{style};"
            f"unicode-range:{ranges};"
            f"src:url(data:font/woff2;base64,{src}) format('woff2')}}`,"
        )
    Path('src/render/tex-fonts.js').write_text(
        '// Generated by scripts/subset-tex-fonts.py: do not edit.\n'
        "// Subsets of MathJax's TeX fonts (Computer Modern), Copyright The MathJax\n"
        '// Consortium, Apache License 2.0: https://www.apache.org/licenses/LICENSE-2.0\n\n'
        '/** @font-face rules for the `ags-tex` family, embedded as data URIs. */\n'
        'export const TEX_FONTS = [\n' + '\n'.join(faces) + "\n].join('');\n"
    )


if __name__ == '__main__':
    main(sys.argv[1])
